#!/usr/bin/env php
<?php
/**
 * Render the landing pages to static HTML for preview or a static fallback deploy.
 *
 * Usage:
 *   php bin/build-static.php                       # relative links (…/index.html), for local or any static host
 *   php bin/build-static.php --base=https://yatomy.com          # real domain in canonical/hreflang
 *   php bin/build-static.php --cta=https://...                    # override the built-in Easy Registration link
 *   php bin/build-static.php --out=/path/to/dir
 *
 * Output: {out}/{lang}/{slug}/index.html for every page × language, plus {out}/index.html.
 */

$root   = dirname( __DIR__ );
$plugin = $root . '/wp-content/plugins/atomy-qr-landing';

require_once $plugin . '/includes/class-renderer.php';
$content = require $plugin . '/includes/content.php';

$opts = getopt( '', array( 'base::', 'cta::', 'out::', 'site::' ) );
$base = isset( $opts['base'] ) ? rtrim( $opts['base'], '/' ) : '';
$cta  = isset( $opts['cta'] ) && $opts['cta'] !== '' ? $opts['cta'] : 'https://us.atomy.com/gate/join/easyreg/v2/22457174';
$out  = isset( $opts['out'] ) ? rtrim( $opts['out'], '/' ) : $root . '/dist';
$site = isset( $opts['site'] ) ? $opts['site'] : 'YAtomy';

$renderer = new Atomy_QR_Landing_Renderer( $content );
$written  = array();

foreach ( $content['pages'] as $key => $page ) {
	$slug = $page['default_slug'];
	foreach ( array_keys( $content['languages'] ) as $lang ) {
		$alternates = array();
		foreach ( array_keys( $content['languages'] ) as $alt ) {
			$alternates[ $alt ] = $base !== '' ? "$base/$alt/$slug/" : "../../$alt/$slug/index.html";
		}
		$ctx = array(
			'cta_url'    => $cta,
			'site_name'  => $site,
			'home_url'   => $base !== '' ? "$base/" : '../../index.html',
			'canonical'  => $base !== '' ? "$base/$lang/$slug/" : '',
			'alternates' => $alternates,
		);
		$html = $renderer->render( $key, $lang, $ctx );
		$dir  = "$out/$lang/$slug";
		if ( ! is_dir( $dir ) && ! mkdir( $dir, 0775, true ) ) {
			fwrite( STDERR, "Cannot create $dir\n" );
			exit( 1 );
		}
		file_put_contents( "$dir/index.html", $html );
		$written[] = array( $key, $lang, "$lang/$slug/", strlen( $html ) );
	}
}

/* Preview index */
$rows = '';
foreach ( $content['pages'] as $key => $page ) {
	$rows .= '<tr><td><strong>' . htmlspecialchars( $page['qr'] ) . '</strong><br><small>' . htmlspecialchars( $page['en']['title'] ) . '</small></td>';
	foreach ( array_keys( $content['languages'] ) as $lang ) {
		$rows .= '<td><a href="' . $lang . '/' . $page['default_slug'] . '/index.html">/' . $lang . '/' . $page['default_slug'] . '/</a></td>';
	}
	$rows .= '</tr>';
}
$index = '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Atomy QR landing pages — preview</title>'
	. '<style>body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:720px;margin:40px auto;padding:0 20px;color:#22304a}table{border-collapse:collapse;width:100%}td,th{border:1px solid #dfe6ef;padding:10px;text-align:left;vertical-align:top}th{background:#f4f7fb}a{color:#1b4f9c}</style></head>'
	. '<body><h1>Atomy QR landing pages — static preview</h1><p>Generated by <code>bin/build-static.php</code>. In WordPress these are served by the plugin at the same paths.</p>'
	. '<table><thead><tr><th>QR code</th><th>EN</th><th>KR</th></tr></thead><tbody>' . $rows . '</tbody></table></body></html>';
file_put_contents( "$out/index.html", $index );

foreach ( $written as $w ) {
	printf( "%-9s %-3s %-22s %6d bytes\n", $w[0], $w[1], $w[2], $w[3] );
}
echo "index    →  index.html\n";
